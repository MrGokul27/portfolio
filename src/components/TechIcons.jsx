export function getSkillIcon(iconKey, size = 28) {
  switch (iconKey) {
    case "html5":
      return <Html5Icon size={size} />;
    case "css3":
      return <Css3Icon size={size} />;
    case "bootstrap":
      return <BootstrapIcon size={size} />;
    case "javascript":
      return <JavaScriptIcon size={size} />;
    case "react":
      return <ReactIcon size={size} />;
    case "tailwind":
      return <TailwindIcon size={size} />;
    case "materialui":
      return <MaterialUIIcon size={size} />;
    case "vite":
      return <ViteIcon size={size} />;
    case "redux":
      return <ReduxIcon size={size} />;
    default:
      return <GenericIcon size={size} label={iconKey} />;
  }
}
